#Huge Type of Arithmetic Operators in Python that support multiple data types and operations.

#Modulo Operator (%): Returns the remainder of a division operation. It can be used with integers and floats.

print(10 % 3)  # Output: 1
print(10.5 % 3)  # Output: 1.5

#Exponentiation Operator (**): Raises a number to the power of another number. It can be used with integers and floats.

print(2**3)  # Output: 8
print(2.5**2)  # Output: 6.25

#Floor Division Operator (//): Performs division and returns the largest integer less than or equal to the result. It can be used with integers and floats.

print(10 // 3)  # Output: 3
print(10.5 // 3)  # Output: 3.0
print(12 // 5)  # Output: 2

